// One-time Spotify login: gets a refresh token and writes app-side/secrets.js.
//
// 1. Create an app at https://developer.spotify.com/dashboard
//    (Web API), add Redirect URI: http://127.0.0.1:8888/callback
// 2. node tools/spotify-auth.mjs <CLIENT_ID> <CLIENT_SECRET>
// 3. Log in in the browser window that opens.
import http from "node:http";
import { exec } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const [clientId, clientSecret] = process.argv.slice(2);
if (!clientId || !clientSecret) {
  console.error("Usage: node tools/spotify-auth.mjs <CLIENT_ID> <CLIENT_SECRET>");
  process.exit(1);
}

const PORT = 8888;
const REDIRECT = `http://127.0.0.1:${PORT}/callback`;
const SCOPES = [
  "user-read-playback-state",
  "user-modify-playback-state",
  "user-read-currently-playing",
  "playlist-read-private",
  "playlist-read-collaborative",
  "user-library-read",
  "user-library-modify",
  "user-read-recently-played",
].join(" ");
const SECRETS_PATH = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "app-side", "secrets.js");

const authUrl = "https://accounts.spotify.com/authorize?" + new URLSearchParams({
  client_id: clientId,
  response_type: "code",
  redirect_uri: REDIRECT,
  scope: SCOPES,
});

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url, `http://127.0.0.1:${PORT}`);
  if (url.pathname !== "/callback") {
    res.writeHead(404).end();
    return;
  }

  const code = url.searchParams.get("code");
  if (!code) {
    res.writeHead(400, { "Content-Type": "text/plain; charset=utf-8" })
      .end("Login failed: " + (url.searchParams.get("error") ?? "no code"));
    return;
  }

  const tokenRes = await fetch("https://accounts.spotify.com/api/token", {
    method: "POST",
    headers: {
      "Content-Type": "application/x-www-form-urlencoded",
      Authorization: "Basic " + Buffer.from(`${clientId}:${clientSecret}`).toString("base64"),
    },
    body: new URLSearchParams({ grant_type: "authorization_code", code, redirect_uri: REDIRECT }),
  });
  const token = await tokenRes.json();

  if (!token.refresh_token) {
    res.writeHead(500, { "Content-Type": "text/plain; charset=utf-8" })
      .end("Token exchange failed: " + JSON.stringify(token));
    console.error("Token exchange failed:", token);
    server.close();
    return;
  }

  writeFileSync(SECRETS_PATH,
    "// Generated by tools/spotify-auth.mjs. Do not share or commit.\n" +
    `export const SPOTIFY_CLIENT_ID = ${JSON.stringify(clientId)};\n` +
    `export const SPOTIFY_CLIENT_SECRET = ${JSON.stringify(clientSecret)};\n` +
    `export const SPOTIFY_REFRESH_TOKEN = ${JSON.stringify(token.refresh_token)};\n`);

  res.writeHead(200, { "Content-Type": "text/plain; charset=utf-8" })
    .end("Done! You can close this tab.");
  console.log("Saved refresh token to", SECRETS_PATH);
  server.close();
});

server.listen(PORT, "127.0.0.1", () => {
  console.log("Opening browser for Spotify login...");
  console.log("If it does not open, visit:\n" + authUrl);
  exec(`start "" "${authUrl}"`);
});
